// End-to-end lift shop flow in a real browser (needs freshly seeded demo data and a running server).
// Usage: node scripts/e2e-shop.mjs <outDir>
import { chromium } from 'playwright';
const base = 'http://localhost:3000';
const out = process.argv[2];
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, acceptDownloads: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
page.on('console', (m) => { if (m.type() === 'error' && !/Failed to load resource/.test(m.text())) errors.push(m.text()); });
await page.goto(`${base}/login`);
await page.locator('[data-testid=demo-CUSTOMER]').nth(1).click();
await page.waitForURL((u) => u.pathname.startsWith('/customer'), { timeout: 30000 });
await page.goto(`${base}/customer/shop/new`);
await page.fill('input[name=projectName]', 'Mehta Heights');
await page.selectOption('select[name=zoneId]', { index: 3 });
await page.fill('textarea[name=address]', 'Plot 12, Baner, Pune');
await page.selectOption('select[name=buildingType]', 'RESIDENTIAL_APARTMENT');
for (const [n, v] of Object.entries({ floors: '6', stops: '6', shaftWidthMm: '1800', shaftDepthMm: '1900', pitDepthMm: '1500', overheadMm: '4300', persons: '6', ratedLoadKg: '408' })) await page.fill(`input[name=${n}]`, v);
await page.selectOption('select[name=powerSupply]', 'THREE_PHASE');
await page.check('input[name=consentContact]'); await page.check('input[name=consentPrivacy]');
await page.click('button:has-text("Continue to packages")');
await page.waitForURL(/packages/, { timeout: 30000 }).catch(async (e) => { await page.screenshot({ path: `${out}/fail.png`, fullPage: true }); throw e; });
await page.screenshot({ path: `${out}/1-packages.png`, fullPage: true });
await page.locator('button:has-text("Customise this package")').nth(1).click();
await page.waitForURL(/cart/, { timeout: 30000 });
const before = await page.locator('.fixed.bottom-0 .text-lg').innerText();
await page.locator('li:has-text("Gold mirror") button:has-text("Choose")').click();
await page.waitForFunction((b) => document.querySelector('.fixed.bottom-0 .text-lg')?.textContent !== b, before, { timeout: 30000 });
const after = await page.locator('.fixed.bottom-0 .text-lg').innerText();
await page.screenshot({ path: `${out}/2-cart.png` });
await page.locator('#checkout button:has-text("Request quotation")').click();
await page.waitForURL(/quotations/, { timeout: 30000 });
await page.screenshot({ path: `${out}/3-quote.png`, fullPage: true });
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('a:has-text("Download PDF")')]);
const path = `${out}/quote.pdf`; await dl.saveAs(path);
console.log(JSON.stringify({ before, after, pdf: dl.suggestedFilename(), errors }));
await browser.close();
